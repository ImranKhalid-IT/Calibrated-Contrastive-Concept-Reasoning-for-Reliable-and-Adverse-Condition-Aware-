def add_fog(img, severity=FOG_SEVERITY):
    """Atmospheric-scattering fog, I = J*t + A*(1-t). Deterministic per severity."""
    t = {0: 1.0, 1: 0.85, 2: 0.70, 3: 0.55, 4: 0.42, 5: 0.30}[severity]
    A = 0.85
    j = img.astype(np.float32) / 255.0
    h = j.shape[0]
    t_map = t * (1.0 - 0.15 * (1 - np.linspace(0, 1, h)))[:, None, None]  # denser at top
    fog = j * t_map + A * (1 - t_map)
    return (np.clip(fog, 0, 1) * 255).astype(np.uint8)


def iou(a, b):
    ix1, iy1 = max(a[0], b[0]), max(a[1], b[1])
    ix2, iy2 = min(a[2], b[2]), min(a[3], b[3])
    inter = max(0.0, ix2 - ix1) * max(0.0, iy2 - iy1)
    ua = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / ua if ua > 0 else 0.0


def gt_boxes(stem, W, H, cls_name):
    path = LABELS_DIR / f"{stem}.txt"
    out = []
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        p = line.split()
        if len(p) < 5 or YOLO_NAMES[int(p[0])] != cls_name:
            continue
        cx, cy, w, h = (float(v) for v in p[1:5])
        out.append([(cx - w / 2) * W, (cy - h / 2) * H, (cx + w / 2) * W, (cy + h / 2) * H])
    return out


# ----------------------------------------------------------------- data download
def _download(url, dest, timeout=120):
    dest.parent.mkdir(parents=True, exist_ok=True)
    with requests.get(url, stream=True, timeout=timeout) as r:
        r.raise_for_status()
        tmp = dest.with_suffix(dest.suffix + ".part")
        with open(tmp, "wb") as f:
            for chunk in r.iter_content(1 << 20):
                if chunk:
                    f.write(chunk)
        tmp.rename(dest)


