def run_example(det, path, gt, target, alt):
    from skimage.segmentation import slic
    clean = np.asarray(PILImage.open(path).convert("RGB"))
    fog = add_fog(clean)
    H, W = fog.shape[:2]
    t_i, a_i = det.idx[target], det.idx[alt]
    rec = dict(coco_id=path.stem, target=target, alternative=alt, gt=gt, fog=fog)

    o = det.match(fog, gt, target)
    rec.update(orig_status=o["status"], orig_label=o["label"], orig_score=o["score"])
    if o["status"] == "missed":
        rec.update(edit=fog, heat=None, edit_status="missed", edit_label="", edit_score=None,
                   p_orig=None, p_edit=None, m_orig=None, m_edit=None, delta_m=None, det_box=None)
        return rec

    box = [float(v) for v in o["box"]]                      # fixed RoI for all edits
    x1, y1 = max(0, int(box[0])), max(0, int(box[1]))
    x2, y2 = min(W, int(round(box[2]))), min(H, int(round(box[3])))
    crop = fog[y1:y2, x1:x2]
    blurred = np.asarray(PILImage.fromarray(fog).filter(
        ImageFilter.GaussianBlur(radius=BLUR_RADIUS)))[y1:y2, x1:x2]

    base = det.roi_logits([fog], box)[0]
    m0 = float(base[t_i] - base[a_i])

    seg = slic(crop, n_segments=N_SEGMENTS, compactness=12.0, sigma=1.0,
               start_label=1, channel_axis=-1)
    jobs = []
    for rid in np.unique(seg):
        mask = seg == rid
        if mask.sum() < max(25, int(0.0025 * mask.size)):
            continue
        e = fog.copy()
        e[y1:y2, x1:x2][mask] = blurred[mask]
        jobs.append((int(rid), mask, e))
    effects = {}
    for k in range(0, len(jobs), BATCH):
        grp = jobs[k:k + BATCH]
        for (rid, _, _), lg in zip(grp, det.roi_logits([g[2] for g in grp], box)):
            effects[rid] = m0 - float(lg[t_i] - lg[a_i])      # positive = supports target

    # heatmap: positive region effects, normalized to [0, 1] per object
    heat = np.zeros(fog.shape[:2], np.float32)
    pos_max = max([v for v in effects.values() if v > 0], default=0.0)
    if pos_max > 0:
        for rid, v in effects.items():
            if v > 0:
                heat[y1:y2, x1:x2][seg == rid] = v / pos_max

    # edit: blur top-effect regions until COVER of the box area
    edit_mask = np.zeros_like(seg, dtype=bool)
    for rid, v in sorted(effects.items(), key=lambda kv: -kv[1]):
        if v <= 0 or (edit_mask.sum() + (seg == rid).sum()) > COVER * seg.size and edit_mask.any():
            break
        edit_mask |= seg == rid
    edit = fog.copy()
    edit[y1:y2, x1:x2][edit_mask] = blurred[edit_mask]

    le = det.roi_logits([edit], box)[0]
    m1 = float(le[t_i] - le[a_i])
    soft = lambda z: np.exp(z - z.max()) / np.exp(z - z.max()).sum()
    e = det.match(edit, gt, target)
    missed = e["status"] == "missed"
    rec.update(edit=edit, heat=heat, edit_status=e["status"], edit_label=e["label"],
               edit_score=e["score"], det_box=box,
               p_orig=float(soft(base)[t_i]), p_edit=float(soft(le)[t_i]),
               m_orig=m0, m_edit=m1, delta_m=None if missed else m1 - m0,
               edited_fraction=float(edit_mask.mean()))
    return rec


