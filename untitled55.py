def coco128_candidates(target):
    ensure_coco128()
    out = []
    for p in sorted(IMAGES_DIR.glob("*.jpg")):
        with PILImage.open(p) as im:
            W, H = im.size
        boxes = [b for b in gt_boxes(p.stem, W, H, target)
                 if min(b[2] - b[0], b[3] - b[1]) >= MIN_BOX_SIDE]
        if boxes:
            out.append((p, max(boxes, key=lambda b: (b[2] - b[0]) * (b[3] - b[1]))))
    return out


