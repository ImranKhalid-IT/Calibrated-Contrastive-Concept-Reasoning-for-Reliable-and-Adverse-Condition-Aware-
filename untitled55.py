EDGE = {"correct": "#2ca02c", "wrong": "#ff7f0e", "missed": "#d62728"}
FILL = {"correct": "#d9f2d9", "wrong": "#ffe5cc", "missed": "#f8d0d0"}


def _crop_view(rec):
    x1, y1, x2, y2 = rec["gt"]
    H, W = rec["fog"].shape[:2]
    s = max(x2 - x1, y2 - y1) * 1.3
    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
    a, b = int(max(0, cx - s / 2)), int(max(0, cy - s / 2))
    c, d = int(min(W, cx + s / 2)), int(min(H, cy + s / 2))
    return a, b, c, d


def _img(ax, arr, view, heat=None, box=None, status=None):
    a, b, c, d = view
    ax.imshow(arr[b:d, a:c])
    if heat is not None:
        ax.imshow(np.ma.masked_where(heat[b:d, a:c] <= 0, heat[b:d, a:c]),
                  cmap="jet", vmin=0, vmax=1, alpha=0.55)
    if box is not None and status:
        ax.add_patch(Rectangle((box[0] - a, box[1] - b), box[2] - box[0], box[3] - box[1],
                               fill=False, ec=EDGE[status], lw=1.0,
                               ls="--" if status == "missed" else "-"))
    ax.set_xticks([]); ax.set_yticks([])
    for sp in ax.spines.values():
        sp.set_linewidth(0.3)


def _label(ax, status, label, score):
    txt = "no detection" if status == "missed" else f"{label}: {score:.2f}"
    ax.text(0.5, -0.05, txt, transform=ax.transAxes, ha="center", va="top", fontsize=4.9,
            bbox=dict(boxstyle="round,pad=0.15", fc=FILL[status], ec=EDGE[status], lw=0.6))


def draw_figure(panels, out_stem):
    plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 6})
    n_p = len(panels)
    fig = plt.figure(figsize=(7.16, 2.75 * n_p + 0.5))
    ph = 2.75 / (2.75 * n_p + 0.5)
    L, Wd, ih = 0.075, 0.915, ph * 0.175
    for pi, (title, contrast, recs) in enumerate(panels):
        y0 = 0.99 - pi * ph
        fig.text(L, y0, title, fontsize=7.5, fontweight="bold", va="top")
        fig.text(L + Wd, y0, f"Fixed contrast: {contrast}", fontsize=6, va="top",
                 ha="right", style="italic")
        r0 = y0 - ph * 0.13 - ih
        r1 = r0 - ph * 0.105 - ih
        r2 = r1 - ph * 0.025 - ih
        cw = Wd / 10
        for k, r in enumerate(recs):
            x, w = L + k * cw + 0.003, cw - 0.006
            fig.text(x + w / 2, y0 - ph * 0.105, r["coco_id"], ha="center", fontsize=4.6)
            view = _crop_view(r)
            gt_or_det = r["det_box"] if r["det_box"] is not None else r["gt"]
            a0 = fig.add_axes([x, r0, w, ih])
            _img(a0, r["fog"], view, box=gt_or_det, status=r["orig_status"])
            _label(a0, r["orig_status"], r["orig_label"], r["orig_score"] or 0)
            a1 = fig.add_axes([x, r1, w, ih])
            _img(a1, r["fog"], view, heat=r["heat"])
            if r["heat"] is None:
                a1.text(0.5, 0.5, "not computed\n(missed)", transform=a1.transAxes,
                        ha="center", va="center", fontsize=4.8, color="#444")
            a2 = fig.add_axes([x, r2, w, ih])
            _img(a2, r["edit"], view, box=gt_or_det, status=r["edit_status"])
            _label(a2, r["edit_status"], r["edit_label"], r["edit_score"] or 0)
            yb = r2 - ph * 0.085
            if r["delta_m"] is None:
                fig.text(x + w / 2, yb, "Δm = N/A\n(missed)", ha="center", va="top",
                         fontsize=5.4, color="#444", fontweight="bold",
                         bbox=dict(boxstyle="round,pad=0.2", fc="#e6e6e6", ec="none"))
            else:
                fig.text(x + w / 2, yb,
                         f"p: {r['p_orig']:.2f}→{r['p_edit']:.2f}\nΔm = {r['delta_m']:+.2f}",
                         ha="center", va="top", fontsize=5.4, color="#b00000",
                         fontweight="bold",
                         bbox=dict(boxstyle="round,pad=0.2", fc="#fbe0e0", ec="none"))
            if k == 0:
                for yy, nm in zip((r0, r1, r2), ("Original\n(fog)", "Region\neffect", "Edited\n(fog)")):
                    fig.text(L - 0.006, yy + ih / 2, nm, ha="right", va="center", fontsize=5.8)

    cax = fig.add_axes([0.80, 0.022, 0.17, 0.004])
    cb = fig.colorbar(plt.cm.ScalarMappable(cmap="jet", norm=plt.Normalize(0, 1)),
                      cax=cax, orientation="horizontal")
    cb.set_label("Region effect on margin (normalized)", fontsize=5.5)
    cb.ax.tick_params(labelsize=5)
    fig.legend(handles=[Patch(fc=FILL["correct"], ec=EDGE["correct"], label="correct class"),
                        Patch(fc=FILL["wrong"], ec=EDGE["wrong"], label="wrong class"),
                        Line2D([], [], color=EDGE["missed"], ls="--", label="no detection (GT box)"),
                        Patch(fc="#e6e6e6", label="Δm = N/A (missed)")],
               loc="lower left", bbox_to_anchor=(0.01, 0.0), ncol=4, fontsize=5.5,
               frameon=False)
    fig.savefig(f"{out_stem}.png", dpi=300)
    fig.savefig(f"{out_stem}.pdf")
    plt.close(fig)


def write_csv(panels, path):
    cols = ["panel", "coco_id", "target", "alternative", "orig_status", "orig_label",
            "orig_score", "edit_status", "edit_label", "edit_score", "p_orig", "p_edit",
            "m_orig", "m_edit", "delta_m", "edited_fraction"]
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for key, (_, _, recs) in panels.items():
            for r in recs:
                w.writerow([key] + [("" if r.get(c) is None else
                                     (f"{r[c]:.4f}" if isinstance(r.get(c), float) else r.get(c)))
                                    for c in cols[1:]])


# ----------------------------------------------------------------- main
def main():
    np.random.seed(SEED)
    det = Detector()
    print("[Fig13] Image source:", "COCO val2017" if USE_VAL2017 else "COCO128")
    results = {}
    for key, title, target, alt, n, skip in PANELS:
        cands = (val2017_candidates(target, skip + n) if USE_VAL2017
                 else coco128_candidates(target))
        chosen = cands[skip:skip + n]
        if not chosen:
            print(f"[Fig13] Panel {key}: no '{target}' images available -> skipped")
            continue
        if len(chosen) < n:
            print(f"[Fig13] Panel {key}: only {len(chosen)} '{target}' images available")
        recs = []
        for i, (p, gt) in enumerate(chosen, 1):
            r = run_example(det, p, gt, target, alt)
            recs.append(r)
            dm = "N/A" if r["delta_m"] is None else f"{r['delta_m']:+.3f}"
            print(f"[Fig13] {key}{i:02d} {p.stem}: orig={r['orig_status']} "
                  f"edit={r['edit_status']} delta_m={dm}")
        results[key] = (title, f"{target} vs. {alt}", recs)

    if not results:
        raise RuntimeError("No panel could be built.")
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    write_csv(results, OUT_DIR / "fig13_results.csv")
    draw_figure(list(results.values()), str(OUT_DIR / "fig13_results"))
    print("[Fig13] Figure:", OUT_DIR / "fig13_results.png")
    print("[Fig13] Data  :", OUT_DIR / "fig13_results.csv")
    print("STEP 6 COMPLETED")


if __name__ == "__main__":
    main()



